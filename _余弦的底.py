"""余弦的"底" —— 为什么 0.47 这个分数**不算高**。

【要看的现象】

`_泛块体检.py` 里量出来：泛块「## 一句话总结」平均 0.478。
看着挺高，其实**跟没命中差不多**。

这个脚本干一件事：拿几个问题，去撞**明确答它的句子**和**明确不答它的句子**，
把分数摆一张表上看 —— 你会看见"不相干"的那几行也有 0.4~0.5。

【一句话原理】

余弦分数**没有"绝对及格线"**，它不是考试分。**分数只有排在一起才有意义。**
所以下面这行"不相干的最高分"，才是这个模型的**地板**。

跑法（先进这个文件夹）：
    cd "D:/CC Switch/问答机器人"
    python _余弦的底.py
"""

import sys

sys.stdout.reconfigure(errors="replace")

import 检索_向量

# (句子, 它答的是第几个问题；None = 谁都不答，专门用来垫底)
问题们 = [
    "闭包是什么",
    "SQL 里 JOIN 怎么用",
    "装饰器是干嘛的",
]
句子们 = [
    ("闭包是一个函数，它记住了外面的变量", 0),
    ("JOIN 把两张表按某列接起来", 1),
    ("装饰器是接收函数、返回函数的函数", 2),
    ("git 提交要写 commit message", None),
    ("今天中午吃了牛肉面", None),
    ("用 requests 发 POST 要传 data", None),
]


def main():
    向量们 = 检索_向量.变成向量们(问题们 + [句 for 句, _ in 句子们])
    问题向量们 = 向量们[: len(问题们)]
    句向量们 = 向量们[len(问题们) :]

    最低的相关 = 9.0
    最高的无关 = 0.0

    问题号 = 0
    for 问题, 问题向量 in zip(问题们, 问题向量们):
        print(f"\n问：{问题}")
        带分 = []
        for (句, 答第几个), 句向量 in zip(句子们, 句向量们):
            分 = 检索_向量.夹角(问题向量, 句向量)
            带分.append((分, 句, 答第几个 == 问题号))
        带分.sort(key=lambda 三: 三[0], reverse=True)
        for 分, 句, 是答案 in 带分:
            尾巴 = "  ← 这才是答它的" if 是答案 else ""
            if 是答案:
                最低的相关 = min(最低的相关, 分)
            else:
                最高的无关 = max(最高的无关, 分)
            print(f"  {分:.3f}   {句}{尾巴}")
        问题号 += 1

    print()
    print("══ 摆完表，看两个数 ══")
    print(f"  答它的那句，最低 {最低的相关:.3f}")
    print(f"  不答它的那些，最高 {最高的无关:.3f}")
    print()
    print("  → 分数**没有及格线**。0.47 落在这两个数之间，等于没命中。")


if __name__ == "__main__":
    main()
