"""接着问：setdefault 里的「塞一个默认的进去」是什么意思。

**「塞」= 字典里真的多了一个键，键的值就是那个默认值本身（不是复制一份）。**
所以后面谁读到 / 写到的，都是同一个东西。

这一幕只看两件事：
  ① 塞完以后，字典的长度变了没有（len 会告诉你）
  ② 你拿在手里的那个，跟字典里存着的那个，是不是同一个（用 is 看，不是 ==）
"""

print("=" * 58)
print("一、塞，就是字典里多了一行")
print("=" * 58)

申请们 = {}
print(f"  一开始          申请们 = {申请们}   len = {len(申请们)}")

壳 = 申请们.setdefault(0, {"id": "", "function": {"name": "", "arguments": ""}})
print(f"  setdefault(0,空壳) 之后")
print(f"                  申请们 = {申请们}   len = {len(申请们)}   ← 多了一行")
print(f"  递给你的 壳 是：  {壳}")
print(f"  它就是字典里那一行吗？壳 is 申请们[0] → {壳 is 申请们[0]}")
print()

壳["id"] = "call_a"
print(f"  我改 壳['id'] = 'call_a'，字典跟着变了吗？")
print(f"                  申请们 = {申请们}")
print("  ★ 会变。因为我改的不是副本，就是那个格子里原本的东西。")
print("    这就是 `壳 = 申请们.setdefault(...)` 之后能一直往里加的理由。")


print()
print("=" * 58)
print("二、反过来：.get() 不塞，你拿到的是孤岛上的一只盒子")
print("=" * 58)

账 = {"甲": []}
拿到 = 账.get("乙", [])        # ← 想"没有就给我一个空的"
print(f"  拿到 = 账.get('乙', []) → {拿到}")
print(f"  账现在是什么样？        {账}   len = {len(账)}   ← 乙根本没进去")

拿到.append("乙的第一笔")
print(f"  往 拿到 里 append 之后：")
print(f"  拿到  = {拿到}")
print(f"  账    = {账}                ← 账里一个字都没多")
print()
print("  ★ 这只盒子飘在孤岛上：你往里装得挺开心，账里看不见。")
print("    这类 bug 不报错、不抛异常，只是数据凭空消失 —— 最贵的那种。")
print("    setdefault 的'塞'，就是不让它飘在外面。")
