import 检索
import 检索_向量

有答案的问题 = [
    "闭包是什么",
    "装饰器是干嘛的",
    "with 语句怎么用",
    "字典怎么按值排序",
    "虚拟环境是干嘛的",
    "asyncio 和线程池怎么选",
    "断点调试怎么打断点",
    "怎么判断输入是不是数字",
    "列表推导式怎么写",
    "pip 和 requirements.txt 的关系",
]

没答案的问题 = [
    "红烧肉怎么做",
    "怎么用 Go 写一个 HTTP 服务",
    "Kubernetes 怎么部署",
    "React 的 useEffect 依赖数组怎么写",
    "公司报销流程是什么",
    "Java 的 JVM 垃圾回收怎么调",
    "网页怎么水平居中一个 div",
    "股票开户要多少钱",
    "吉他 C 和弦怎么按",
    "北京明天天气怎么样",
]


def 最高分(问题: str, 块向量们: list[list[float]]) -> float:
    问题向量 = 检索_向量.变成向量们([问题])[0]
    return max(检索_向量.夹角(问题向量, 块向量) for 块向量 in 块向量们)


def main() -> None:
    块们 = 检索.可用块()
    块向量们 = 检索_向量.建块向量(块们)
    print(f"可用块：{len(块们)}")
    print()

    print("=== 有答案的（不该被拒）===")
    有分 = []
    for 问题 in 有答案的问题:
        分 = 最高分(问题, 块向量们)
        有分.append(分)
        print(f"  {分:.4f}  {问题}")

    print()
    print("=== 没答案的（该被拒）===")
    没分 = []
    for 问题 in 没答案的问题:
        分 = 最高分(问题, 块向量们)
        没分.append(分)
        print(f"  {分:.4f}  {问题}")

    print()
    print(f"有答案：最低 {min(有分):.4f}  平均 {sum(有分) / len(有分):.4f}")
    print(f"没答案：最高 {max(没分):.4f}  平均 {sum(没分) / len(没分):.4f}")
    print(f"两堆中间的空隙：{min(有分) - max(没分):+.4f}")


if __name__ == "__main__":
    main()
