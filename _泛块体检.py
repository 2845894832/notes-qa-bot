# -*- coding: utf-8 -*-
"""泛块体检 —— 把"什么都沾一点"的块，量成三张表。

【要量的是什么】

换班之后，前几名里混着「## 进度」「### 关键收获」这种块。
它们没错，是**什么都沾一点** —— 余弦相似度对这种块也给个中等分。

【三个量法，前两个看出来一件事：指标选错，问题就像不存在】

量法① 数"每个块被几个问题挑中"：
    ❌ 量出来是 0 —— 15 个问题 × 前 3 = 45 个位置，44 个块各只出现一次，只有 1 块出现 2 次。

    ⭐ **不是没有泛块，是尺子拿错了。** 泛块的"身份证"是**标题**，不是块 ——
       同一句「### 关键收获」在 28 篇笔记里各有一份，成了几十个**不同的块**，
       每块当然都只被挑中一次。

量法② 按**标题**归类再数：
    ✅ 立刻现形 —— 「## 进度」3 次、「### 关键收获」3 次（45 个位置占掉 6 个）。

量法③ 数"跟每个问题的**平均分**"：
    ✅ 换个角度看同一件事 —— 真讲某件事的块只跟一两个问题像；什么都沾一点的块跟每个都像一点。
       泛块「## 一句话总结」  平均 0.478  最高 0.667
       真块「### 二、闭包」    平均 0.421  最高 0.599

    ⭐ **平均分高 = 泛；最高分高 = 专。** 余弦只看单次，它分不清这两种。

【这把尺子怎么用】

跟 `_对比_撞词vs向量.py` 一样：**给你看数的，不是给你改的。**
这是改之前的成绩单 —— 下一步给"标题加权"改完，再跑一遍这张表，两个数一比就知道有没有用。

跑法（必须先 cd 进这个文件夹）：
    cd "D:/CC Switch/问答机器人"
    python _泛块体检.py

输出存一份的话：
    python _泛块体检.py > _泛块体检_改前.txt
"""

import sys

sys.stdout.reconfigure(errors="replace")

import 检索_向量

每次取几块 = 3

# 15 个"真有人会问"的问题，尽量铺开不同主题
问题们 = [
    "闭包是什么",
    "装饰器是干嘛的",
    "with 语句怎么用",
    "asyncio 和线程池怎么选",
    "怎么给函数加类型注解",
    "logging 怎么配置",
    "SQL 里 JOIN 怎么用",
    "requests 怎么发 POST",
    "迭代器和生成器有什么区别",
    "异常处理里 finally 什么时候跑",
    "pathlib 怎么拼路径",
    "正则表达式怎么抓数字",
    "虚拟环境是干嘛的",
    "字典怎么按值排序",
    "多进程和线程的区别",
]


def 取前几(块们, 块向量们, 问题向量):
    """一个问题的前几名：(分数, 块) 排好序。"""
    带分 = [(检索_向量.夹角(问题向量, 块向量), 块) for 块, 块向量 in zip(块们, 块向量们)]
    带分.sort(key=lambda 对: 对[0], reverse=True)
    return 带分


def 表1_每问前几(块们, 块向量们, 问题向量们):
    print("══ 表 1：每个问题挑出来的前 3 ══")
    for 问题, 问题向量 in zip(问题们, 问题向量们):
        print(f"\n问：{问题}")
        for 分, 块 in 取前几(块们, 块向量们, 问题向量)[:每次取几块]:
            print(f"  {分:.3f}   正文 {len(块['正文']):>5} 字   {块['标题'].strip()}")


def 表2_按标题数(块们, 块向量们, 问题向量们):
    print()
    print("══ 表 2：45 个位置，按【标题】归类，出现 2 次以上的 ══")
    print()
    上榜标题: dict[str, int] = {}
    for 问题向量 in 问题向量们:
        for 分, 块 in 取前几(块们, 块向量们, 问题向量)[:每次取几块]:
            标题 = 块["标题"].strip()
            上榜标题[标题] = 上榜标题.get(标题, 0) + 1

    for 标题, 次数 in sorted(上榜标题.items(), key=lambda 对: 对[1], reverse=True):
        if 次数 >= 2:
            print(f"  {次数} 次   {标题}")

    print()
    print(f"  （45 个位置里，不同标题一共 {len(上榜标题)} 个）")


def 表3_平均分(块们, 块向量们, 问题向量们):
    print()
    print("══ 表 3：跟 15 个问题的【平均分】 ══")
    行 = []
    for 块, 块向量 in zip(块们, 块向量们):
        分们 = [检索_向量.夹角(问题向量, 块向量) for 问题向量 in 问题向量们]
        行.append((sum(分们) / len(分们), max(分们), 块))
    行.sort(key=lambda 三: 三[0], reverse=True)

    print()
    print("  ── 平均分最高的 15 块（最泛的）──")
    print(f"  {'平均':>6} {'最高':>6}  {'正文':>6}   标题")
    for 平均, 最高, 块 in 行[:15]:
        print(f"  {平均:6.3f} {最高:6.3f}  {len(块['正文']):>5}字   {块['标题'].strip()}")

    print()
    print("  ── 平均分最低的 5 块（最专的）──")
    for 平均, 最高, 块 in 行[-5:]:
        print(f"  {平均:6.3f} {最高:6.3f}  {len(块['正文']):>5}字   {块['标题'].strip()}")


def main():
    块们 = 检索_向量.可用块()
    块向量们 = 检索_向量.建块向量(块们)
    问题向量们 = 检索_向量.变成向量们(问题们)

    print(f"可用块 {len(块们)} 个   问题 {len(问题们)} 个   每个取前 {每次取几块} 块")
    print()

    表1_每问前几(块们, 块向量们, 问题向量们)
    表2_按标题数(块们, 块向量们, 问题向量们)
    表3_平均分(块们, 块向量们, 问题向量们)


if __name__ == "__main__":
    main()
