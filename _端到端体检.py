# -*- coding: utf-8 -*-
"""端到端体检 —— 整条线一起量：检索挑块 → 拼提示词 → 模型回答。

前面十一站的尺子只量"对的块进没进前 3"；这把尺子量**答案本身**。

跑法：
    cd "D:/CC Switch/问答机器人"
    python _端到端体检.py

一次 20 题，约 1.5~2 分钟（每题要问两次接口：问题变向量 + 模型回答）。
每题还会把挑中的 3 块、答案原文打印出来 —— 日志很长是正常的。

规矩：**只改标着 `<<< 填这里` 的地方，别的一个字都别动。一共 3 处。**
⚠️ 判据那一行（`判拒了`）**先别改** —— 它就是今天的陷阱，跑完再动。
"""

import sys
import time

import 主程序
import 检索

sys.stdout.reconfigure(errors="replace")

# 笔记里确实有答案的 10 题（就是标准答案表那 10 题）
有答案的问题 = [
    "闭包是什么",
    "装饰器是干嘛的",
    "with 语句怎么用",
    "字典怎么按值排序",
    "虚拟环境是干嘛的",
    "asyncio 和线程池怎么选",
    "断点调试怎么打断点",
    "怎么判断输入是不是数字",
    "列表推导式怎么写",
    "pip 和 requirements.txt 的关系",
]

# 笔记里压根没有的 10 题（模型应该老老实实说"笔记里没有"）
没答案的问题 = [
    "红烧肉怎么做",
    "怎么用 Go 写一个 HTTP 服务",
    "Kubernetes 怎么部署",
    "React 的 useEffect 依赖数组怎么写",
    "公司报销流程是什么",
    "Java 的 JVM 垃圾回收怎么调",
    "网页怎么水平居中一个 div",
    "股票开户要多少钱",
    "吉他 C 和弦怎么按",
    "北京明天天气怎么样",
]


def 判拒了(答案: str) -> bool:
    """尺子：这个答案算不算"拒答"（说"笔记里没有"）。

    ⚠️ 先照这个粗写法跑，别改。
       跑完你会发现有两条"有答案"的题被判成了误拒 ——
       去看那两条的答案原文，再想这一行该怎么改。
    """
    return "[[无答案]]" in 答案


def main() -> None:
    块们 = 检索.可用块()
    print(f"可用块：{len(块们)}")

    有误拒 = 0
    没误答 = 0
    总耗时 = 0.0
    总题数 = len(有答案的问题) + len(没答案的问题)

    for 类别, 题们 in (("有", 有答案的问题), ("没", 没答案的问题)):
        for 问题 in 题们:
            t = time.perf_counter()

            # <<< 填这里（1/3）：把这个问题交给整条线。
            #     提示：调用 主程序.回答一个问题(问题, 块们)，它会 return 答案；
            #           把它接住，存进 答案。
            答案 = 主程序.回答一个问题(问题,块们)

            耗时 = time.perf_counter() - t
            总耗时 += 耗时

            拒了 = 判拒了(答案)

            if 类别 == "有" and 拒了:
                有误拒 += 1

            if 类别 == "没" and not 拒了:
                没误答 += 1

            print(f"  [{类别}] {'拒答' if 拒了 else '作答'} {耗时:4.1f}s  {问题}")
            time.sleep(1)  # 别把免费接口打太快

    print()
    print(f"有答案的 {len(有答案的问题)} 题：误拒 {有误拒} 条")
    print(f"没答案的 {len(没答案的问题)} 题：误答（没拒） {没误答} 条")
    print(f"平均耗时：{总耗时 / 总题数:.1f}s")


if __name__ == "__main__":
    main()
