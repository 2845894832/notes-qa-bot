    print(f"工具总次数 {sum(r['工具次数'] for r in 记录们)}") 
    print(f"失败       {sum(r['失败'] for r in 记录们)} 次")
    print(f"拒答       {sum(1 for r in 记录们 if r  ['拒答'])} 题")
    print(f"耗时中位数 {statistics.median(r['耗时秒']   for r in 记录们):.2f} 秒")  