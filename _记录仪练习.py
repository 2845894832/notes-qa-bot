import time
import json
import statistics
import time
from datetime import datetime
from pathlib import Path

记录文件 = Path(__file__).with_name("练习记录.jsonl")

# 假剧本：问题 → 每一轮"模型递了几张申请单"
#   带 ! 的名字 = 这只手会失败（第 4 课那种）
#   空列表 = 这一轮它不递申请，说人话了 → 收工
剧本 = {
    "闭包是什么":      [["search_notes"], []],                     # 2 轮，1 次工具
    "9 月餐饮多少":    [["read_ledger!"], ["read_ledger"], []],    # 第一次失败，改参数再来
    "今天天气怎么样":  [[]],                                       # 1 轮收工，一次工具都没伸
}
假耗时 = {"闭包是什么": 1.2, "9 月餐饮多少": 0.9, "今天天气怎么样": 0.6}
假回答 = {"今天天气怎么样": "[[无答案]]"}     # 只有它拒答


def 假执行(名字: str) -> tuple[str, bool]:
    """冒充 执行申请()：返回 (结果文字, 失败了没)。"""
    if 名字.endswith("!"):
        return "【工具报错】ValueError: 账本里没有这个月", True
    return "查到 3 块笔记", False


def 跑一问(问题: str) -> str:
    """跑完一整个 Agent 循环，顺便记账。"""
    开始 = time.time()
    最后 = ""

    # ============================================================
    # TODO 1 —— 三个计数器，都从 0 起
    #   请求次数：每发一次请求加一（= 转了几轮）
    #   工具次数：每执行一张申请单加一
    #   失败次数：假执行 返回 True 的时候加一
    # ============================================================

    请求次数 = 0    # ← 改成你要的数（这一行是给你看形状的，值不对）
    工具次数 = 0
    失败次数 = 0

    for 申请们 in 剧本[问题]:
        请求次数 += 1                       # ← 这一行已经写好了，别动

        if not 申请们:                       # 它说人话了 → 收工
            最后 = 假回答.get(问题, "……（它说的话）")
            break

        for 名字 in 申请们:
            工具次数 += 1                   # ← 这一行也写好了
            结果, 失败了 = 假执行(名字)
            # ========================================================
            # TODO 1b —— 失败了就把 失败次数 加一
            # ========================================================
            if 失败了:
                失败次数 += 1   

    耗时 = 假耗时[问题]                      # 演示用：真主程序里是 time.time() - 开始

    # ============================================================
    # TODO 2 —— 把这一问写成一行，追加到 记录文件
    #
    #   一行 = {
    #       "时间": datetime.now().isoformat(timespec="seconds"),
    #       "问题": 问题,
    #       "轮数": 请求次数,
    #       "工具次数": 工具次数,
    #       "失败": 失败次数,
    #       "耗时秒": 耗时,
    #       "拒答": 最后 里有没有 [[无答案]]   ← 用 in
    #   }
    #
    #   然后：
    #       记录文件.open("a", encoding="utf-8")
    #       文件.write(json.dumps(一行, ensure_ascii=False) + "\n")
    #
    #   ⚠️ 整个写文件过程要包在 try/except OSError 里：
    #      记录仪是副业，写不进去也只能打一行提示，**不能让回答跟着挂掉**。
    # ============================================================
    一行 = {
        "时间": datetime.now().isoformat(timespec="seconds"),
        "问题": 问题,
        "轮数": 请求次数,
        "工具次数": 工具次数,
        "失败": 失败次数,
        "耗时秒": 耗时,
        "拒答": "[[无答案]]" in 最后
    }
    try:
        with 记录文件.open("a", encoding="utf-8") as 文件:
            文件.write(json.dumps(一行, ensure_ascii=False) + "\n") 
    except OSError as e: 
        print(f"⚠️ 写记录失败：{e}")

    return 最后


def 读记录() -> list[dict]:
    """把文件读回来：一行 → 一个 dict。"""
    记录们 = []
    for 行 in 记录文件.read_text(encoding="utf-8").splitlines():
        if 行.strip():
            记录们.append(json.loads(行))
    return 记录们


if __name__ == "__main__":
    记录文件.write_text("", encoding="utf-8")     # 每次从头跑，好对数

    for 问题 in 剧本:
        print(f"===== 问：{问题} =====")
        print(跑一问(问题))
        print("-" * 46)

    # ================================================================
