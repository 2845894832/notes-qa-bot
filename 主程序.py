# -*- coding: utf-8 -*-
"""项目第 ③ 步：把四步串成一条线。

    问题 ──► 检索挑出相关的几块 ──► 拼成一段 prompt ──► 发给模型 ──► 打印答案

⚠️ 关键认知：模型**没读过你的笔记**。
   它回答时能看到的，只有这一次请求里发给它的那些字。
   所以第 ② 步挑得准不准，直接决定它答得好不好。
"""

import sys

import 检索
import 问模型

取几块 = 3


def 拼提示词(问题: str, 块们: list[dict]) -> str:
    """把挑中的几块正文，跟问题拼成一段话，交给模型。"""
    # TODO 1 —— 把每一块的正文取出来，用两个换行连成一大段
    #   提示： 节选 = "\n\n".join(块["正文"] for 块 in 块们)
    节选 = "\n\n".join(块["正文"] for 块 in 块们)

    # TODO 2 —— 用 f-string 拼出下面这个形状（照抄这几句话，只把 {} 换成真东西）：
    #
    #       下面是给你的笔记节选：
    #
    #       {节选}
    #
    #       根据上面的笔记回答：{问题}
    #       如果笔记里没有，就说“笔记里没有”。
    #
    #   写完 return 出去。
    return f"""下面是给你的笔记节选：

  {节选}

  根据上面的笔记回答：{问题}
  如果笔记里没有，就说“笔记里没有”。"""


def 回答一个问题(问题: str, 块们: list[dict]) -> None:
    # ← 把原来 主程序() 里那 7 行搬进来
    #    （从 挑中的 = 检索.找相关(...) 开始，一直到 print(答案)）
    挑中的 = 检索.找相关(问题, 块们, 取几块)

    print(f"===== 问：{问题}，挑中 {len(挑中的)} 块 =====")
    for 块 in 挑中的:
        print(f"  {块['文件']}:{块['行号']}  {块['标题']}")
    print("-" * 50)

    提示词 = 拼提示词(问题, 挑中的)
    答案 = 问模型.问一句(提示词)
    print(答案)


def 主程序() -> None:
    块们 = 检索.可用块()
    print("笔记问答机器人。输入问题按回车；什么都不输直接回车就退出。")
    while True:
        问题 = input("\n问：")
        if not 问题:
            print("拜拜。")
            break
        回答一个问题(问题, 块们)


if __name__ == "__main__":
    # TODO 3 —— 命令行入口。先看清楚 sys.argv 是什么东西：
    #   它就是"你在命令行上敲的每一个词"，组成一个列表；第 0 个永远是脚本名自己。
    #
    #       python 主程序.py                        → ["主程序.py"]
    #       python 主程序.py "闭包是什么"            → ["主程序.py", "闭包是什么"]
    #       python 主程序.py 闭包 是什么             → ["主程序.py", "闭包", "是什么"]
    #
    #   所以"带没带问题"看长度：len(sys.argv) > 1 就是带了。
    #   问题本身用 " ".join(sys.argv[1:]) 拼回来 ——
    #   （这样上面第三种跑法也能得到完整的"闭包 是什么"，
    #     代价是词之间的空格会变成一个空格，所以问句还是建议加引号）
    #
    #   要写的分支（三行，写完在这儿就完事）：
    #       如果 len(sys.argv) > 1  →  问这一个（调 回答一个问题(问题, 检索.可用块())），然后 return
    #       否则                    →  原来的 主程序()（进交互模式）
    if len(sys.argv) > 1:
        回答一个问题(" ".join(sys.argv[1:]), 检索.可用块())
    else:
        主程序()
