# 【那个「开关」单独说一下】
# ════════════════════════════════════════════════════════════════
#
# 要解决的问题：笔记里的代码长这样 ——
#
#     ```python
#     # 创建 —— 用圆括号
#     students = []
#     ```
#
# 那个 `# 创建` 是注释，不是标题。可它长得跟 `## 标题` 一样，都是 # 开头。
# 不挡的话，笔记会被【假标题】剁碎。
#
# 挡法：
#
#     if 行.strip().startswith("```"):
#         在代码块里 = not 在代码块里      # ★ 翻一下
#
#     if not 在代码块里 and 行.startswith("#"):   # ★ 不在代码块里才算标题
#
# 为什么"翻一下"就够：``` 永远成对出现 ——
#
#     ```      ← 第 1 个：False → True    进代码块
#     # 注释   ← 在代码块里 → 不算标题 ✅
#     ```      ← 第 2 个：True → False    出来了
#     ## 标题  ← 不在 → 算标题 ✅
#
# 实测差距（真的 24 篇笔记）：
#     有开关 → 502 块
#     没开关 → 587 块（多出 85 个垃圾块）
#
# 那 85 个"标题"长这样：
#     # 创建 — 用圆括号 ()      # 索引 — 用方括号 []
#     # 去重 — 秒杀             # ❌ 错误        # ✅ 正确
# 一眼就是代码注释。
#
# ════════════════════════════════════════════════════════════════
# 【`continue` 是干什么的】
# ════════════════════════════════════════════════════════════════
#
# 意思："这一轮到此为止，跳回 for 拿下一行，下面的一概不看。"
#
# 三条岔路是【三个独立的 if】，不是 if/else。靠 continue 保证每行只走一条。
#
# 去掉它会怎样 —— 围栏行会被扔进箱子两次：
#
#     遇到 ```python
#       → 走岔路1：翻开关，正文行们.append(行)     ← 第一次扔
#       → 没有 continue，继续往下执行
#       → 撞上岔路2的 if：这行以 ` 开头不是 #，不成立 → 跳过
#       → 落到最后一行：正文行们.append(行)         ← 第二次扔！
#
# 实测（同一份 12 行文件）：
#     有 continue → ## 列表 装 9 行   ✅
#     没 continue → ## 列表 装 11 行  ❌（两行围栏各出现两次）
#
# ⚠️ 这种 bug 不会报错，只会让正文悄悄变样 —— 最难查的一类。
#    continue 看着像可有可无的润色，其实是逻辑的一部分。
#
