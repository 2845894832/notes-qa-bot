# -*- coding: utf-8 -*-
"""把日期笔记切成一块一块，每块带自己的正文。

════════════════════════════════════════════════════════════════
【这个文件干什么】
════════════════════════════════════════════════════════════════
把一篇笔记切成块。每块 = 一个标题 + 它下面的内容，一直到下一个标题。

    输入（9 行）           输出（4 块）
    # 我的小抄             '(文件开头)'  正文=''          ← 第 1 行之前，空的
    开头随便写点            '# 我的小抄'  正文='开头随便写点'
                          '## 标题A'    正文='A 的内容第一行\nA 的内容第二行'
    ## 标题A               '## 标题B'    正文='B 的内容'
    A 的内容第一行
    A 的内容第二行
    ## 标题B
    B 的内容

块长这样（一个字典）：
    {"文件": "python-learning-2026-09-11.md", "行号": 120,
     "标题": "## 武器选择", "正文": "I/O 密集用线程……"}

════════════════════════════════════════════════════════════════
【核心思路：装箱】
════════════════════════════════════════════════════════════════
手上有一个"当前箱子"，一行一行往下走，看到内容就往里扔。
一看到新标题，就把当前箱子封上、贴好标签，放到一边，换个空箱子继续。
走完全部行，手上还剩最后一个没封的箱子 —— 再封一次。

════════════════════════════════════════════════════════════════
【整条流程】
════════════════════════════════════════════════════════════════
    ① 读文件    → 一个字符串            p.read_text(encoding="utf-8")
    ② 按行切开  → 一行一个元素           .splitlines()
    ③ 一行行走  → 顺便带着行号           enumerate(行们, 1)
    ④ 遇到 ```  → 翻开关                 在代码块里 = not 在代码块里
    ⑤ 遇到标题  → 封上一箱、换新箱        收块()
    ⑥ 走完      → 最后那个箱子还没封      收块()

跟「笔记整理」的 生成清单.py 是同一套 ``` 状态机，但这里简单得多：
    - 不要主题、不要栈继承（那是用来分类的，C3 只要纯文本块）
    - 多一个「正文」字段（打分要拿正文来数词）

只读工具：只读笔记，不写任何东西。
"""

from pathlib import Path

目录 = Path("D:/CC Switch")


def 切一个文件(p: Path) -> list[dict]:
    """把一个文件切成块。"""
    # 装最终结果。先开个空篮子，一边走一边往里放
    块们: list[dict] = []

    # 整个文件读成【一个字符串】→ 按换行切成【一行一个元素的列表】
    行们 = p.read_text(encoding="utf-8").splitlines()

    # ── 四个变量 = 当前这个箱子上贴的东西 ──────────────────────
    # （"当前"两个字是关键：它们记的是"我手上这个箱子现在长什么样"）
    在代码块里 = False  # 我在不在 ``` 里面（见下面「开关」）
    当前标题 = "(文件开头)"  # 箱子标签。第 1 行之前先假设有这么个空箱子
    当前行号 = 0  # 这个箱子从第几行开始
    正文行们: list[str] = []  # 箱子里装的内容

    def 收块() -> None:
        """封箱：把当前那几个变量打包成一个字典，扔进 块们。"""
        块们.append(
            {
                "文件": p.name,
                "行号": 当前行号,
                "标题": 当前标题,
                # 攒的那些行，用换行拼回一整段文字
                "正文": "\n".join(正文行们).strip(),
            }
        )

    # ── 一行一行走。岔路只有三条，每行只会走其中一条 ────────────
    for i, 行 in enumerate(行们, 1):  # 写 1，是为了让行号跟记事本对得上

        # 岔路 1：这行是代码围栏 ```  ────────────────────────────
        # 围栏永远成对出现（开一个关一个），所以"翻一下"正好对上"进去、出来"。
        # 跟电灯开关一样：按一下亮，再按一下灭。
        if 行.strip().startswith("```"):
            在代码块里 = not 在代码块里
            正文行们.append(行)  # 围栏这行自己也是笔记的一部分，不能丢
            continue  # ★ 办完立刻跳回 for，下面一概不看

        # 岔路 2：这行是真标题  ────────────────────────────────
        # 必须 "不在代码块里"，否则代码里的注释（# 创建 —— 用圆括号）
        # 会被当成标题，把笔记剁碎。
        if not 在代码块里 and 行.startswith("#"):
            收块()  # 先把上一箱封了
            当前标题 = 行.strip()  # 换新箱子，贴标签
            当前行号 = i
            正文行们 = []  # 新箱子是空的
            continue  # ★ 同上，办完就跳走

        # 岔路 3：普通内容  ────────────────────────────────────
        # 这一行没有 if 包着 —— 前面两条都 continue 跳走了，
        # 所以"能走到这儿"，本身就说明它是普通内容。
        正文行们.append(行)

    # ── ⑥ 循环走完了，最后那个箱子还开着，手动封一次 ──────────────
    # 因为"封箱"是"遇到新标题"才触发的，走到文件末尾时没有下一个标题来触发它。
    收块()
    return 块们


def 切全部() -> list[dict]:
    """扫 目录 下全部 python-learning-*.md，返回所有块。"""
    块们: list[dict] = []
    # sorted 是为了让每次跑出来的顺序都一样
    for p in sorted(目录.glob("python-learning-*.md")):
        # 用 extend 不是 append —— append 会把整个列表塞成一个元素
        块们.extend(切一个文件(p))
    return 块们


if __name__ == "__main__":
    块们 = 切全部()
    print(f"切出 {len(块们)} 块")
    print()
    print("--- 第 1 块 ---")
    print("文件:", 块们[0]["文件"], "行号:", 块们[0]["行号"])
    print("标题:", 块们[0]["标题"])
    print("正文前 100 字:")
    print(块们[0]["正文"][:100])
    print()
    print("--- 挑一块有正文的看看（找第一块正文超过 200 字的） ---")
    for 块 in 块们:
        if len(块["正文"]) > 200:
            print("文件:", 块["文件"], "行号:", 块["行号"])
            print("标题:", 块["标题"])
            print("正文长度:", len(块["正文"]), "字")
            print("正文前 200 字:")
            print(块["正文"][:200])
            break


