import 切块
import 检索_向量

最短正文 = 50                   # 正文短于这个字、又不含 `代码` 的块，多半是空壳 / 清单，扔掉
不参加排名的标题 = {"## 进度"}   # 台账类标题：每篇笔记都有一节，装的是"今天做到第几关"


def 拆词(文本: str) -> set[str]:
    """每 2 个字切一刀，装进集合。中英一视同仁。"""
    干净 = "".join(字 for 字 in 文本 if 字.isalnum())
    return {干净[i : i + 2] for i in range(len(干净) - 1)}


def 建权重表(块们: list[dict]) -> dict[str, float]:
    """每个词值多少钱 = 1 / 它在几个块里出现过。越罕见越值钱。"""
    出现过: dict[str, int] = {}
    for 块 in 块们:
        for 词 in 拆词(块["标题"] + 块["正文"]):
            出现过[词] = 出现过.get(词, 0) + 1
    return {词: 1 / 次 for 词, 次 in 出现过.items()}


def 打分(问题: str, 块: dict, 权重: dict[str, float]) -> float:
    """这个块拿多少分。标题里撞上的词算 3 倍。"""
    标题词 = 拆词(块["标题"])
    块词 = 标题词 | 拆词(块["正文"])
    撞上 = 拆词(问题) & 块词
    return sum(权重.get(词, 0) * (3 if 词 in 标题词 else 1) for 词 in 撞上)


def 找相关(问题: str, 块们: list[dict], 取几块: int = 3) -> list[dict]:
    """给每块打分，返回分数最高的前几块。

    2026-10-12 换班：算分从"数撞了几个字"改成"比向量夹角"。
    对上面几层来说什么都没变 —— 名字、参数、返回的东西都一样。
    """
    return 检索_向量.找相关(问题, 块们, 取几块)


def 不是垃圾块(块: dict) -> bool:
    """这块有没有资格参加排名：有资格 True，是垃圾 False。

    2026-10-17 新增。之前只看"正文 >= 20 字"，于是：
      - 25 字的空壳混进了前 3（09-02 那个「## 五、虚拟环境与包管理」）
      - 「## 进度」一连占掉第 1、2 名，把真答案挤到第 3
    垃圾的定义是"它答不了任何问题"，跟问题像不像**无关** —— 所以这层在打分前面。

    2026-10-17 晚改：光看字数会误伤"短而完整"的答案。第 9、10 题的正确块
    只有 27 / 26 字（「在可疑处 print 中间值」「先 .isdigit() 再转」），
    被 50 字门槛直接扔了，根本没参加排名。
    现在短块只要含 `代码` 就留下；状态 / 清单类空壳（没有反引号）照扔。
    """
    if len(块["正文"]) < 最短正文 and "`" not in 块["正文"]:
        return False
    if 块["标题"].strip() in 不参加排名的标题:
        return False
    return True


def 可用块() -> list[dict]:
    """切全部 + 扔掉光杆标题 + 扔掉空壳/台账。"""
    return [块 for 块 in 切块.切全部() if 不是垃圾块(块)]


if __name__ == "__main__":
    块们 = 可用块()
    print(f"可用块：{len(块们)}")
    print()
    for 问题 in [
        "闭包是什么",
        "asyncio 和线程池怎么选",
        "装饰器是干嘛的",
        "with 语句怎么用",
    ]:
        print(f"===== 问：{问题} =====")
        for 块 in 找相关(问题, 块们):
            print(f"  {块['文件']}:{块['行号']}  {块['标题']}")
        print()
