# -*- coding: utf-8 -*-
"""从笔记里挑出跟问题最相关的几块。

打分 = 问题里的词，在块里撞上了几个：
    每个词值 1 / 它在多少个块里出现过   ← 废话词自动贬值（"什么"到处都是 → 几乎不值钱）
    标题里撞上的算 3 倍                 ← 标题是作者手写的"这块讲什么"，是强信号
    正文少于 20 字的块直接扔掉           ← 光杆标题没东西发给模型

只读工具：只读笔记，不写任何东西。
"""

import 切块

最短正文 = 20  # 正文短于这个字的块，是光杆标题，扔掉


def 拆词(文本: str) -> set[str]:
    """每 2 个字切一刀，装进集合。中英一视同仁。"""
    干净 = "".join(字 for 字 in 文本 if 字.isalnum())
    return {干净[i : i + 2] for i in range(len(干净) - 1)}


def 建权重表(块们: list[dict]) -> dict[str, float]:
    """每个词值多少钱 = 1 / 它在几个块里出现过。越罕见越值钱。"""
    出现过: dict[str, int] = {}
    for 块 in 块们:
        for 词 in 拆词(块["标题"] + 块["正文"]):
            出现过[词] = 出现过.get(词, 0) + 1
    return {词: 1 / 次 for 词, 次 in 出现过.items()}


def 打分(问题: str, 块: dict, 权重: dict[str, float]) -> float:
    """这个块拿多少分。标题里撞上的词算 3 倍。"""
    标题词 = 拆词(块["标题"])
    块词 = 标题词 | 拆词(块["正文"])
    撞上 = 拆词(问题) & 块词
    return sum(权重.get(词, 0) * (3 if 词 in 标题词 else 1) for 词 in 撞上)


def 找相关(问题: str, 块们: list[dict], 取几块: int = 3) -> list[dict]:
    """给每块打分，返回分数最高的前几块。"""
    权重 = 建权重表(块们)  # 块多、问得多的话，这一步该拿到外面算一次复用
    带分的 = [(打分(问题, 块, 权重), 块) for 块 in 块们]
    带分的.sort(key=lambda 对: 对[0], reverse=True)
    return [对[1] for 对 in 带分的[:取几块]]


def 可用块() -> list[dict]:
    """切全部 + 扔掉没正文的光杆标题。"""
    return [块 for 块 in 切块.切全部() if len(块["正文"]) >= 最短正文]


if __name__ == "__main__":
    块们 = 可用块()
    print(f"可用块：{len(块们)}")
    print()
    for 问题 in [
        "闭包是什么",
        "asyncio 和线程池怎么选",
        "装饰器是干嘛的",
        "with 语句怎么用",
    ]:
        print(f"===== 问：{问题} =====")
        for 块 in 找相关(问题, 块们):
            print(f"  {块['文件']}:{块['行号']}  {块['标题']}")
        print()
