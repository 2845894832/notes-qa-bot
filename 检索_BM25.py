# -*- coding: utf-8 -*-
"""BM25 —— 比"撞词法"聪明一点的按字面找。跟 检索_向量.py 并列，是第三套找法。

它跟 检索.py 里那个老 `打分()` 是同一个思路（数词撞上了没有），
只多了三个修正：

    ① 提了几次       tf：一块里出现 5 次，比出现 1 次更像在讲它
    ② 这个词多冷门    idf：`的` 满书都是，不值钱；`闭包` 很少见，值钱
    ③ 这块多厚        长度归一化：500 字的块天然提得多，要按长度打折

只有这三样，没有别的。公式在 `混合检索-复习速查.md` 里。

规矩：**只改标着 `<<< 填这里` 的地方，别的一个字都别动。一共 3 处。**
⚠️ 标点一律英文半角（逗号 , 括号 () 引号 ""）。
"""

import math
import re
from collections import Counter

k1 = 1.5    # ① 词频的"饱和速度"：提 10 次不会比提 3 次值钱 3 倍
b = 0.75    # ③ 长度打折的力度：0 = 完全不管长短，1 = 完全按长度打折

# 英文 / 数字按整词切；中文两个字切一刀。
# （跟 检索.拆词 的差别：这里要**数次数**，所以返回 list，不是 set。）
段样式 = re.compile(r"[A-Za-z0-9_]+|[一-鿿]+")


def 分词(文本: str) -> list[str]:
    词们: list[str] = []
    for 段 in 段样式.findall(文本):
        if 段[0].isascii():
            词们.append(段.lower())
        else:
            词们.extend(段[i : i + 2] for i in range(len(段) - 1))
            if len(段) == 1:
                词们.append(段)
    return 词们


def 建统计(块们: list[dict]) -> dict:
    """一次性数好：每块的词频、每块多长、每个词在几块里出现过。

    这三样对应三个旋钮：词频 → ①，df → ②，长度 → ③。
    """
    词频们: list[Counter[str]] = []
    长度们: list[int] = []
    df: Counter[str] = Counter()

    for 块 in 块们:
        词们 = 分词(块["正文"]) + 分词(块["标题"])
        词频们.append(Counter(词们))
        长度们.append(len(词们))
        for 词 in set(词们):
            df[词] += 1

    return {
        "词频们": 词频们,
        "长度们": 长度们,
        "df": df,
        "平均长度": sum(长度们) / len(长度们),
        "总数": len(块们),
    }


def 一个词的idf(词: str, 统计: dict) -> float:
    """② 这个词多值钱：越少见的词 idf 越大。

    df = 有几块提到过它。公式（照抄，换个词名就行）：
        idf = log(1 + (总共几块 - df + 0.5) / (df + 0.5))
    """
    df = 统计["df"].get(词, 0)
    # <<< 填这里（1/3）：把上面的公式写成一行 return。
    idf = math.log(1 + (统计["总数"] - df + 0.5) / (df + 0.5))
    #     提示：math.log(...)。0.5 不能省，它是防止"一次没出现"时除零的。
    return idf


def 长度折扣(第几块: int, 统计: dict) -> float:
    """③ 这块要打几折：越长，同一个词的分量越轻。

        折扣 = 1 - b + b * (这块长度 / 平均长度)

    一块跟平均一样长 → 折扣 = 1（不打折）；比平均长 → 折扣 > 1（分被除得更多）。
    """
    长度 = 统计["长度们"][第几块]
    # <<< 填这里（2/3）：把上面的公式写成一行 return。
    return 1 - b + b * (长度 / 统计["平均长度"])


def 这块得几分(问题: str, 第几块: int, 统计: dict) -> float:
    """①+②+③ 合起来：问题里的每个词，各算一项，全加起来。

    每一项长这样（BM25 的全部内容就这一行）：

        idf(词) * tf * (k1 + 1) / (tf + k1 * 长度折扣)

    tf      = 这个词在这块里出现了几次
    tf == 0 = 这块根本没提 → 直接跳过（不然会把分拉低）
    """
    分 = 0.0
    折扣 = 长度折扣(第几块, 统计)

    for 词 in set(分词(问题)):
        tf = 统计["词频们"][第几块][词]
        if tf == 0:
            continue
        # <<< 填这里（3/3）：把上面那一行公式写出来，加到 分 上。
        #     三样现成的：一个词的idf(词, 统计)、tf、折扣；k1 在最上面。
        分 += 一个词的idf(词, 统计) * tf * (k1 + 1) / (tf + k1 * 折扣)

    return 分


def 排榜(问题: str, 块们: list[dict], 统计: dict | None = None) -> list[int]:
    """给所有块打分，返回名次（从高到低）的**下标**列表。"""
    if 统计 is None:
        统计 = 建统计(块们)
    return sorted(range(len(块们)), key=lambda i: 这块得几分(问题, i, 统计), reverse=True)


def 找相关(问题: str, 块们: list[dict], 取几块: int = 3) -> list[dict]:
    """跟 检索.py / 检索_向量.py 同名同参数同返回 —— 前几块。"""
    统计 = 建统计(块们)
    榜 = 排榜(问题, 块们, 统计)
    return [块们[i] for i in 榜[:取几块]]


