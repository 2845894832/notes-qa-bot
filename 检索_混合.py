"""混合检索：向量榜 + BM25 榜，各取前 20，用 RRF 合成一张总榜。

    cd "D:/CC Switch/问答机器人"
    python 检索_混合.py

为什么要混合（一句话）：
    向量认"意思"（闭包 ≈ 封闭），BM25 认"字面"（`dict.get` 就得原样出现）。
    两套榜各看各的，很可能互补。

规矩：**只改标着 `<<< 填这里` 的地方。一共 1 处。**
⚠️ 标点一律英文半角。
"""

import 检索_BM25
import 检索_向量

粗筛取几块 = 20   # 每张榜只让前 20 名参加融合（第 21 名以后的"票"不值钱）
RRF的k = 60


def 融合(榜们: list[list[int]], 总块数: int, k: int = RRF的k) -> list[int]:
    """几张榜 → 一张总榜。

    ⚠️ 两套算法的分**不是同一个单位**：向量是 0~1 的夹角，BM25 是几十上百的加法。
    直接相加，BM25 会把向量吞掉。所以 RRF 只看"名次"，不看"分数"：

        第 1 名投 1/(k+1) 票，第 2 名投 1/(k+2) 票，……
        两套榜的票加起来，重新排名。

    一张榜里排第 5、另一张里也排第 5 → 票最多；
    只有一张榜看好它 → 票少一半。
    """
    分表: dict[int, float] = {}

    for 榜 in 榜们:
        for 名次, i in enumerate(榜[:粗筛取几块], 1):
            # <<< 填这里（1/1）：第 i 块从这张榜拿到多少票？
            #     提示：1 / (k + 名次)。k 在最上面。
            票 = 1 / (k + 名次) 
            分表[i] = 分表.get(i, 0.0) + 票

    # 没进任何前 20 的块，分记 0 —— 不然它们会从分表里消失
    for i in range(总块数):
        分表.setdefault(i, 0.0)

    return sorted(分表, key=lambda i: 分表[i], reverse=True)


def 向量榜(问题: str, 块们: list[dict]) -> list[int]:
    """纯向量的名次榜（下标从高到低）。"""
    块向量们 = 检索_向量.建块向量(块们)
    问题向量 = 检索_向量.变成向量们([问题])[0]
    带分 = [
        (检索_向量.夹角(问题向量, 块向量), i)
        for i, 块向量 in enumerate(块向量们)
    ]
    带分.sort(key=lambda 对: 对[0], reverse=True)
    return [i for _, i in 带分]


def 找相关(问题: str, 块们: list[dict], 取几块: int = 3) -> list[dict]:
    """跟 检索.py / 检索_向量.py 同名同参数同返回。"""
    统计 = 检索_BM25.建统计(块们)
    总榜 = 融合([向量榜(问题, 块们), 检索_BM25.排榜(问题, 块们, 统计)], len(块们))
    return [块们[i] for i in 总榜[:取几块]]


