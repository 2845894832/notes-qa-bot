class Test拆词(unittest.TestCase):
    """拆词(文本) = 把字串里的字母和汉字留下、每 2 个字切一刀，装进集合。"""

    def test_正常(self):
        self.assertEqual(检索.拆词("abcd"),{"ab", "bc", "cd"})

    def test_空字符串(self):
        # 第 4 题：拆词("") —— 一个字的空串，一刀也切不出来。
        # 期望：一个**空的集合**。
        # <<< 填这里：把下面这行补完整（两个参数）。
        self.assertEqual(检索.拆词(""),set())

    def test_中文每两个字一刀(self):
        # 第 5 题：拆词("闭包是什么")
        # 期望：{"闭包", "包是", "是什", "什么"}  ← 四个词照抄，中间用英文逗号
        # <<< 填这里：把 期望 那一半补上。
        self.assertEqual(检索.拆词("闭包是什么"), {"闭包", "包是", "是什", "什么"})

    def test_丢掉标点和空格(self):
        # 第 6 题：拆词("a, b!")
        # 期望：{"ab"}   ← 逗号、空格、感叹号先被扔掉，剩下 "ab" 只够切一刀
        # <<< 填这里：把两个参数补上 —— 左边 检索.拆词("a, b!")，右边是那个集合。
        self.assertEqual(检索.拆词("a, b!"),{"ab"})


class Test建权重表(unittest.TestCase):
    """建权重表(块们) = 每个词值多少钱 = 1 ÷ 它在几个块里出现过。越罕见越值钱。"""

    def test_只出现过一次就值一元(self):
        # 第 7 题：只有一块笔记，标题就是 "闭包"，正文空着。
        # "闭包" 这个词只出现过 1 次 → 1 ÷ 1 = 多少？
        块们 = [{"标题": "闭包", "正文": ""}]
        # <<< 填这里：把 期望 补上。
        self.assertEqual(检索.建权重表(块们)["闭包"],1.0)

    def test_出现两次就减半(self):
        # 第 8 题：两块笔记，标题都是 "闭包"，正文都空着。
        # "闭包" 出现了 2 次 → 1 ÷ 2 = 多少？
        块们 = [
              {"标题": "闭包", "正文": ""},
              {"标题": "闭包", "正文": ""},
         ]
        # <<< 填这里：两块笔记先是空的，照上一道的样子摆进去（标题都写 "闭包"）。
        # <<< 填这里：再补一句断言 —— 检索.建权重表(块们)["闭包"] 应该等于多少。
        self.assertEqual(检索.建权重表(块们)["闭包"],0.5)


class Test打分(unittest.TestCase):
    """打分(问题, 块, 权重) = 问题里的词在块里撞上了几个，每个值多少钱；标题里撞上的算 3 倍。"""

    def test_标题里的词算三倍(self):
        权重 = {"闭包": 1.0}
        块 = {"标题": "闭包", "正文": ""}
        self.assertEqual(检索.打分("闭包", 块, 权重),3.0)

    def test_正文里撞上的词不算三倍(self):
        # 第 9 题：权重表说 "闭包" 值 1.0。
        # 这一块的标题不是"闭包"，正文里才有 —— 撞是撞上了，但不在标题里，所以不乘 3。
        权重 = {"闭包": 1.0}
        块 = {"标题": "其他地方", "正文": "闭包"}
        # <<< 填这里：把 期望 补上。
        self.assertEqual(检索.打分("闭包", 块, 权重), 1.0)

    def test_一个词都没撞上(self):
        # 第 10 题：问 "闭包"，那块讲的是装饰器 —— 一个词都没撞上。
        # 提示：一个都没撞上时，求和的是个空筐。
        权重 = {"闭包": 1.0, "装饰器": 1.0}
        块 = {"标题": "装饰器", "正文": "装饰器是给函数加料"}
        # <<< 填这里：把两个参数补上。
        self.assertEqual(检索.打分("闭包",块,权重),0.0)


class Test找相关(unittest.TestCase):
    """找相关(问题, 块们, 取几块) = 挑出最像的几块，像的排前面。"""

    def test_得分高的排前面(self):
        块们 = [
            {"标题": "闭包", "正文": "闭包是一个函数，记住了外面的变量"},
            {"标题": "装饰器", "正文": "装饰器是给函数加料"},
        ]
        self.assertEqual(检索.找相关("闭包", 块们)[0]["标题"],"闭包")

    def test_块不够就全给(self):
        # 第 11 题：手里只有 2 块，张嘴要 3 块 —— 给不出 3 块，那就把这 2 块全给出来。
        # 断言的是**条数**：len(结果) 应该等于几？
        块们 = [
            {"标题": "闭包", "正文": "闭包是一个函数，记住了外面的变量"},
            {"标题": "装饰器", "正文": "装饰器是给函数加料"},
        ]
        # <<< 填这里：把 期望 补上。
        self.assertEqual(len(检索.找相关("闭包", 块们, 取几块=3)), 2)


class Test闭包检索(unittest.TestCase):
    """当初是"反面用例"：钉住一个已知 bug —— 问"闭包是什么"，讲闭包的块排不进前 3（第 7、8 名）。

    ✅ 2026-10-12 它绿了：检索换成向量版以后，闭包块排到第 1、4 名。
       所以 `@unittest.expectedFailure` 摘掉了 —— 从"钉住 bug"变成"守住它别回来"。
    """
    def test_标题讲闭包的块应该进前3(self):
        块们 = 检索.可用块()
        结果 = 检索.找相关("闭包是什么", 块们)
        标题们 = [块["标题"] for 块 in 结果]
        self.assertTrue(any("闭包" in 标题 for 标题 in 标题们), f"前三名里没有讲闭包的块，实际是：{标题们}")


